var express = require('express');
var router  = express.Router();
var TargetStage = require('../../../models/Lead_Config/pipeline_stage_pulse/target_stage');

router.post('/Save', function (req, res) {
    try {
        TargetStage.Save_Target_Stage(req.body, function (err, rows) {
            if (err) return res.json(err);
            res.json(rows[0]);
        });
    } catch (e) { res.json(e); }
});

router.get('/Search', function (req, res) {
    try {
        TargetStage.Search_Target_Stage(req.query.search || '', function (err, rows) {
            if (err) return res.json(err);
            res.json(rows[0]);
        });
    } catch (e) { res.json(e); }
});

router.get('/Get/:id', function (req, res) {
    try {
        TargetStage.Get_Target_Stage(req.params.id, function (err, rows) {
            if (err) return res.json(err);
            res.json(rows[0]);
        });
    } catch (e) { res.json(e); }
});

router.get('/Delete/:id', function (req, res) {
    try {
        TargetStage.Delete_Target_Stage(req.params.id, function (err, rows) {
            if (err) return res.json(err);
            res.json(rows[0]);
        });
    } catch (e) { res.json(e); }
});

module.exports = router;
